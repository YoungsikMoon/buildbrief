// docs/planning-template/request-template.md is the canonical template.
const fs = require('node:fs');
const path = require('node:path');

const VERSION = '2026-10-01.1';
const root = path.join(__dirname, '..');
const destination = path.join(root, 'dist/planning-template.js');
const text = fs.readFileSync(path.join(root, 'docs/planning-template/request-template.md'), 'utf8')
  .replace(/\r\n?/g, '\n').trim();
const common = fs.readFileSync(path.join(root, 'docs/planning-template/common-instructions.md'), 'utf8')
  .replace(/\r\n?/g, '\n').trim();
const output = `// Generated by node scripts/planning-template.cjs. Do not edit directly.
(function (root) {
  'use strict';
  const api = ${JSON.stringify({ version: VERSION, text, common })};
  root.BriefPlanningTemplate = api;
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
})(typeof window !== 'undefined' ? window : globalThis);
`;

if (process.argv.length > 3 || (process.argv[2] && process.argv[2] !== '--check')) {
  console.error('Usage: node scripts/planning-template.cjs [--check]');
  process.exitCode = 1;
} else if (process.argv[2] === '--check') {
  if (!fs.existsSync(destination) || fs.readFileSync(destination, 'utf8').replace(/\r\n?/g, '\n') !== output) {
    console.error('Planning template is stale. Run node scripts/planning-template.cjs.');
    process.exitCode = 1;
  } else console.log('Planning template is current.');
} else {
  fs.writeFileSync(destination, output, 'utf8');
  console.log('Generated dist/planning-template.js.');
}
