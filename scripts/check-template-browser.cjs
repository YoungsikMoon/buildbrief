const assert = require('node:assert/strict'), fs = require('node:fs'), path = require('node:path');
module.exports = async function ({ page, context, go, validate, width }) {
  const stored = () => page.evaluate(() => { const w = JSON.parse(localStorage.getItem(BriefProjects.KEY)); return w.projects.find(p => p.id === w.activeId); });
  const side = async selector => { const target = page.locator(selector); if (!await target.isVisible()) await page.locator('#toggle-navigation').click(); return target; };
  const open = async () => { await go(5); await page.locator('#next-button').click(); await page.locator('#show-prompt').click(); };
  const close = () => page.locator('#close-prompt').click();
  const editor = page.locator('#prompt-preview-text'), enabled = page.locator('#planning-template-enabled');
  const shot = async label => { if (process.env.PLANNING_SCREENSHOTS) { fs.mkdirSync(process.env.PLANNING_SCREENSHOTS, { recursive: true }); await page.screenshot({ path: path.join(process.env.PLANNING_SCREENSHOTS, `${label}-${width}.png`) }); } };
  const expected = () => page.evaluate(() => { const w = JSON.parse(localStorage.getItem(BriefProjects.KEY)), p = w.projects.find(p => p.id === w.activeId); return BriefReport.report(p.answers, true, p.notes, p.recommendations, p.planningTemplate, p.promptDrafts); });
  await page.reload(); await go(5);
  assert.equal(await page.locator('.planning-template,#planning-template-enabled').count(), 0, 'The memo step has no prompt configuration');
  const memo = '모드와 무관하게 보존할 메모';
  await page.locator('#input-open_questions').fill(memo);
  const before = await stored(), progress = await page.locator('#mobile-progress').innerText();
  await page.locator('#next-button').click();
  assert.equal(await page.locator('#report-view #copy-prompt,#copy-contents,.prompt-preview').count(), 0);
  assert.equal(await page.locator('#show-prompt').innerText(), 'AI에 전달할 프롬프트 보기');
  await page.locator('#show-prompt').click();
  assert(await page.locator('#prompt-dialog').isVisible());
  assert.equal(await page.evaluate(() => document.activeElement.id), 'prompt-title');
  await page.keyboard.press('Tab'); assert.equal(await page.evaluate(() => document.activeElement.id), 'close-prompt');
  assert.equal(await enabled.isChecked(), false);
  assert.equal((await stored()).planningTemplate, null);
  assert.equal(await page.locator('#planning-template-editor,#planning-template-text').count(),0);
  assert(await editor.isEditable());
  assert(await page.locator('#reset-prompt').isHidden());
  assert.equal(await enabled.getAttribute('role'), 'switch');
  assert((await enabled.boundingBox()).width >= 76, 'The switch keeps its full track width');
  assert((await page.locator('#prompt-mode-help').boundingBox()).width <= 28, 'Help icon stays compact');
  await page.locator('#prompt-mode-help').click();
  assert.equal(await page.locator('#prompt-mode-help').getAttribute('aria-expanded'), 'true');
  for (const text of ['기본','고급','장점','고려할 점','요청 범위']) assert((await page.locator('#prompt-mode-comparison').innerText()).includes(text));
  await validate(); await shot('prompt-help');
  await page.locator('#prompt-mode-help').click();
  assert(await page.locator('#prompt-mode-comparison').isHidden());
  await shot('prompt-basic');
  const defaults = await page.evaluate(() => ({ version: BriefPlanningTemplate.version, text: BriefPlanningTemplate.text }));
  await context.grantPermissions(['clipboard-read','clipboard-write'], {origin:new URL(page.url()).origin});
  let basic;
  for (const advanced of [false,true,false]) {
    await enabled.setChecked(advanced);
    const text = await expected();
    assert.equal(await page.locator('#prompt-preview-text').inputValue(), text);
    assert.equal(text.includes(defaults.text), advanced);
    assert(text.includes('AGENTS.md') && text.includes('docs/tasks/<작업-id>.md'));
    await page.locator('#copy-prompt').click();
    assert.equal((await page.evaluate(() => navigator.clipboard.readText())).replace(/\r\n?/g,'\n'), text);
    assert((await page.locator('#prompt-copy-status').innerText()).includes('복사했어요'));
    if (!advanced) { basic ??= text; assert.equal(text,basic); }
    else { assert.notEqual(text,basic); await shot('prompt-advanced'); }
  }
  const basicCustom = '나만의 기본 프롬프트\n' + basic;
  // Replacing the full JSON prompt also lays out thousands of textarea lines in Chrome.
  await editor.fill(basicCustom, { timeout: 30000 });
  assert.equal((await stored()).promptDrafts.basic,basicCustom);
  assert(await page.locator('#reset-prompt').isVisible());
  await enabled.focus(); await page.keyboard.press('Space'); assert(await enabled.isChecked());
  assert((await editor.inputValue()).includes(defaults.text));
  await editor.fill(''); assert(await page.locator('#copy-prompt').isDisabled());
  assert.equal((await stored()).promptDrafts.advanced,'');
  const custom = '\n  내 프로젝트 요청\n</textarea><img id="template-attack" src=x onerror="window.templateAttack=1">\n<script>window.templateAttack=1</script>\n마지막 줄  ';
  await editor.fill(custom); assert(await page.locator('#copy-prompt').isEnabled());
  await enabled.uncheck(); assert.equal((await stored()).promptDrafts.advanced,custom);
  assert.equal(await editor.inputValue(),basicCustom);
  await enabled.check(); assert.equal(await editor.inputValue(),custom);
  assert.equal(await page.locator('#template-attack,#prompt-dialog script').count(),0);
  assert.equal(await page.evaluate(() => window.templateAttack),undefined);
  assert.equal(await page.locator('#mobile-progress').innerText(),progress);
  assert.deepEqual((await stored()).answers,before.answers);
  const customPrompt = await expected(); assert(customPrompt.includes(custom));
  assert.equal(await page.locator('#prompt-preview-text').inputValue(),customPrompt);
  await page.evaluate(() => Object.defineProperty(navigator,'clipboard',{configurable:true,value:{writeText:async()=>{throw new Error('Test clipboard denied');}}}));
  const fallbackPromise = page.waitForEvent('download'); await page.locator('#copy-prompt').click();
  assert.equal(fs.readFileSync(await (await fallbackPromise).path(),'utf8'),customPrompt);
  assert((await page.locator('#prompt-copy-status').innerText()).includes('파일로'));
  await page.evaluate(() => { delete navigator.clipboard; });
  await page.keyboard.press('Escape'); assert(await page.locator('#prompt-dialog').isHidden());
  assert.equal(await page.evaluate(() => document.activeElement.id),'show-prompt');
  await page.locator('#show-prompt').click(); assert.equal(await page.locator('#prompt-preview-text').inputValue(),customPrompt); await close();
  const download = page.waitForEvent('download'); await (await side('#export-answers')).click();
  const backupText = fs.readFileSync(await (await download).path(),'utf8'), backup = JSON.parse(backupText);
  assert.deepEqual(backup.planningTemplate,(await stored()).planningTemplate);
  assert.deepEqual(backup.promptDrafts,{basic:basicCustom,advanced:custom});
  await (await side('#add-project')).click(); await page.locator('#project-name').fill('독립 프로젝트');
  await page.locator('#project-name-form button[type="submit"]').click(); await open();
  assert(!await enabled.isChecked()); assert.equal((await stored()).planningTemplate,null);
  assert.deepEqual((await stored()).promptDrafts,{});
  await enabled.check(); assert((await editor.inputValue()).includes(defaults.text));
  await editor.fill('다른 프로젝트 요청'); await close();
  await (await side('#project-select')).selectOption(before.id); await open();
  assert(await enabled.isChecked()); assert.equal(await editor.inputValue(),custom); await close();
  await page.reload(); assert(await page.locator('#guide-view').isVisible()); await open();
  assert(await enabled.isChecked()); assert.equal(await editor.inputValue(),custom); await close();
  await page.locator('#import-file').setInputFiles({name:'template-backup.json',mimeType:'application/json',buffer:Buffer.from(backupText)});
  await page.waitForFunction(id => JSON.parse(localStorage.getItem(BriefProjects.KEY)).activeId !== id,before.id);
  await open(); assert.deepEqual((await stored()).promptDrafts,backup.promptDrafts);
  assert.equal(await page.locator('#template-attack,#prompt-dialog script').count(),0);
  // New answers must not silently overwrite the saved prompt. Restore rebuilds it explicitly.
  await close(); await go(5); await page.locator('#input-open_questions').fill(memo+' 추가 답변'); await open();
  assert.equal(await editor.inputValue(),custom);
  const handlers=page.listeners('dialog'); page.removeAllListeners('dialog');
  const reset=async accept=>{const asked=page.waitForEvent('dialog'), clicked=page.locator('#reset-prompt').click();const dialog=await asked;await dialog[accept?'accept':'dismiss']();await clicked;};
  try {
    await reset(false); assert.equal(await editor.inputValue(),custom);
    await reset(true); assert((await editor.inputValue()).includes(defaults.text));
    assert((await editor.inputValue()).includes(memo+' 추가 답변'));
    assert.equal(await page.evaluate(()=>document.activeElement.id),'prompt-preview-text');
    assert.deepEqual((await stored()).promptDrafts,{basic:basicCustom});
    assert(await page.locator('#reset-prompt').isHidden());
    assert.deepEqual((await stored()).planningTemplate,{enabled:true,...defaults});
    await enabled.uncheck(); assert.equal(await editor.inputValue(),basicCustom);
    await reset(true); assert.deepEqual((await stored()).promptDrafts,{});
    assert(!(await editor.inputValue()).includes(defaults.text));
  } finally { for(const handler of handlers)page.on('dialog',handler); }
  assert.equal(await page.locator('#mobile-progress').innerText(),progress);
  assert.equal((await stored()).answers.open_questions,memo+' 추가 답변');
  await page.evaluate(()=>{window.originalStorageSet=Storage.prototype.setItem;Storage.prototype.setItem=()=>{throw new Error('QuotaExceededError');};});
  await editor.fill('저장 실패 시에도 복사 가능한 수정본');
  assert((await page.locator('#prompt-copy-status').innerText()).includes('저장하지 못했어요'));
  await page.locator('#copy-prompt').click();
  assert.equal(await page.evaluate(()=>navigator.clipboard.readText()),'저장 실패 시에도 복사 가능한 수정본');
  await page.evaluate(()=>{Storage.prototype.setItem=window.originalStorageSet;delete window.originalStorageSet;});
  await editor.fill('저장 다시 성공');assert.equal((await stored()).promptDrafts.basic,'저장 다시 성공');
  await shot('prompt-edited');
  await page.evaluate(()=>document.documentElement.style.fontSize='200%');await validate();
  const bounds=await page.locator('#prompt-dialog').boundingBox();assert(bounds.x>=0&&bounds.x+bounds.width<=width+1);
  await page.evaluate(()=>document.documentElement.style.fontSize='');await close();await go(5);
  console.log(`Prompt modal browser checks passed: ${width}px`);
};
